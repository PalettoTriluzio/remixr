"""AI edits of an existing flip: a list of EditOp applied in order.

Sections are addressed by marker name (every marker with that name), "all",
or "bars A-B". Inserting/removing bars shifts everything after the point
(clips, patterns, automation, chords, markers); items across a cut are split.
Each op returns an Italian line for the UI; ops that cannot be applied add a
note instead of failing the whole edit.
"""
from __future__ import annotations

import re
import secrets

from app.flip.generate import ENERGY_LEVEL
from app.flip.recipe import HARMONY_TRACK, MAX_BARS, Builder, apply_fx, uid
from app.models import AutoPoint, EditOp, EditRequest, EditResponse, FlipClip, FlipProject, FlipTrack, Marker, PatternClip, Sidechain

GEN = {"drums": ("drums", None), "bass": ("bass", None), "chords": ("keys", "Accordi"), "arp": ("keys", "Arpeggio")}
SOURCE = {"vocals": "vocals", "other": "other", "mix": "mix", "orig_drums": "drums", "orig_bass": "bass"}
LABEL = {
    "drums": "beat", "bass": "basso", "chords": "accordi", "arp": "arpeggio", "vocals": "voce", "other": "altro",
    "mix": "mix", "orig_drums": "batteria originale", "orig_bass": "basso originale", "harmony": "seconda voce",
}
SHAPES = {  # param, from, to
    "fade_in": ("volume", 0.0, 1.0), "fade_out": ("volume", 1.0, 0.0),
    "filter_open": ("lowpass", 0.3, 1.0), "filter_close": ("lowpass", 1.0, 0.3), "rise": ("highpass", 0.75, 0.0),
}


class EditError(ValueError):
    pass


def _new_id() -> str:
    return secrets.token_hex(4)


# ---------------------------------------------------------------- addressing

def _total(p: FlipProject) -> float:
    return float(p.bars * p.beats_per_bar)


def ranges(p: FlipProject, section: str) -> list[tuple[float, float]]:
    s = (section or "all").strip().lower()
    if s in ("all", "tutto", "tutta", ""):
        return [(0.0, _total(p))]
    m = re.search(r"(\d+)\s*-\s*(\d+)", s)
    if m:
        a, b = sorted((int(m.group(1)), int(m.group(2))))
        bpb = p.beats_per_bar
        return [(float((a - 1) * bpb), float(min(b * bpb, _total(p))))]
    hits = [mk for mk in p.markers if mk.name.lower() == s] or [mk for mk in p.markers if mk.name.lower().startswith(s)]
    if not hits:
        raise EditError(f"sezione «{section}» non trovata")
    return [(mk.start, mk.end) for mk in hits]


def _point(p: FlipProject, after: str) -> float:
    a = (after or "end").strip().lower()
    if a in ("start", "inizio"):
        return 0.0
    if a in ("end", "fine", ""):
        return _total(p)
    return max(b for _, b in ranges(p, after))


def _is_target(track: FlipTrack, target: str) -> bool:
    if target in GEN:
        kind, name = GEN[target]
        return track.kind == kind and (name is None or track.name == name or (target == "chords" and track.name != "Arpeggio"))
    return False


def _gen_tracks(p: FlipProject, targets: list[str]) -> list[FlipTrack]:
    return [t for t in p.tracks if any(_is_target(t, x) for x in targets)]


def _clip_matches(track: FlipTrack, clip: FlipClip, target: str) -> bool:
    if target == "harmony":
        return clip.harmony != 0 or track.name == HARMONY_TRACK
    return target in SOURCE and clip.source == SOURCE[target] and clip.harmony == 0


def _tracks_of(p: FlipProject, targets: list[str]) -> list[FlipTrack]:
    """Tracks touched by targets (generated by role, audio by what they hold)."""
    out = _gen_tracks(p, targets)
    for t in p.tracks:
        if t.kind == "audio" and t not in out and any(_clip_matches(t, c, x) for c in t.clips for x in targets):
            out.append(t)
    return out


# ---------------------------------------------------------------- cutting / shifting

def _split_clip(c: FlipClip, x: float) -> tuple[FlipClip | None, FlipClip | None]:
    end = c.at_beat + c.length_beats
    if x <= c.at_beat:
        return None, c
    if x >= end:
        return c, None
    d = x - c.at_beat
    left = c.model_copy(update={"length_beats": d})
    if c.loop:
        right = c.model_copy(update={"id": _new_id(), "at_beat": x, "length_beats": end - x})
        return left, right
    # Stretched: split the source slice proportionally (reversed plays from the end).
    f = d / c.length_beats
    span = c.src_end - c.src_start
    if c.reverse:
        t = c.src_end - f * span
        l_src, r_src = (t, c.src_end), (c.src_start, t)
    else:
        t = c.src_start + f * span
        l_src, r_src = (c.src_start, t), (t, c.src_end)
    left = left.model_copy(update={"src_start": l_src[0], "src_end": l_src[1], "src_beats": max(0.01, c.src_beats * f)})
    right = c.model_copy(update={"id": _new_id(), "at_beat": x, "length_beats": end - x,
                                 "src_start": r_src[0], "src_end": r_src[1], "src_beats": max(0.01, c.src_beats * (1 - f))})
    return left, right


def _split_pattern(c: PatternClip, x: float) -> tuple[PatternClip | None, PatternClip | None]:
    end = c.at_beat + c.length_beats
    if x <= c.at_beat:
        return None, c
    if x >= end:
        return c, None
    return (c.model_copy(update={"length_beats": x - c.at_beat}),
            c.model_copy(update={"id": _new_id(), "at_beat": x, "length_beats": end - x}))


def _cut(items: list, a: float, b: float, split) -> list:
    """Remove [a, b) from clips/patterns, keeping what is outside."""
    out = []
    for c in items:
        left, rest = split(c, a)
        if left is not None:
            out.append(left)
        if rest is not None:
            _, right = split(rest, b)
            if right is not None:
                out.append(right)
    return out


def _cut_track(t: FlipTrack, a: float, b: float, only=None) -> None:
    if t.kind == "audio":
        keep = [c for c in t.clips if only is not None and not only(c)]
        hit = [c for c in t.clips if only is None or only(c)]
        t.clips = keep + _cut(hit, a, b, _split_clip)
    else:
        t.patterns = _cut(t.patterns, a, b, _split_pattern)


def _fresh_ids(items: list) -> None:
    seen: set[str] = set()
    for c in items:
        if c.id in seen:
            c.id = _new_id()
        seen.add(c.id)


def _shift_marks(marks: list, at: float, delta: float) -> list:
    out = []
    for m in marks:
        if m.end <= at:
            out.append(m)
        elif m.start >= at:
            out.append(m.model_copy(update={"start": m.start + delta, "end": m.end + delta}))
        else:  # spans the point: grows (insert) or shrinks (delete)
            out.append(m.model_copy(update={"end": max(at, m.end + delta)}))
    return out


def insert_gap(p: FlipProject, at: float, length: float) -> None:
    for t in p.tracks:
        if t.kind == "audio":
            t.clips = _cut(t.clips, at, at, _split_clip)
            for c in t.clips:
                if c.at_beat >= at:
                    c.at_beat += length
        else:
            t.patterns = _cut(t.patterns, at, at, _split_pattern)
            for c in t.patterns:
                if c.at_beat >= at:
                    c.at_beat += length
        _fresh_ids(t.clips if t.kind == "audio" else t.patterns)
        for param, pts in t.automation.items():
            t.automation[param] = [AutoPoint(beat=pt.beat + length if pt.beat >= at else pt.beat, value=pt.value) for pt in pts]
    p.chords = _shift_marks(p.chords, at, length)
    # A marker that starts at the point moves; the new section goes in front of it.
    p.markers = [m if m.end <= at else m.model_copy(update={"start": m.start + length, "end": m.end + length}) if m.start >= at
                 else m.model_copy(update={"end": m.end + length}) for m in p.markers]
    p.bars = min(256, p.bars + int(round(length / p.beats_per_bar)))


def delete_range(p: FlipProject, a: float, b: float) -> None:
    d = b - a
    for t in p.tracks:
        _cut_track(t, a, b)
        items = t.clips if t.kind == "audio" else t.patterns
        for c in items:
            if c.at_beat >= b - 1e-9:
                c.at_beat -= d
        _fresh_ids(items)
        for param, pts in t.automation.items():
            t.automation[param] = [AutoPoint(beat=pt.beat - d if pt.beat >= b else pt.beat, value=pt.value)
                                   for pt in pts if not (a <= pt.beat < b)]
    p.chords = [c for c in _shift_marks([c for c in p.chords if not (c.start >= a and c.end <= b)], b, -d)]
    p.markers = [m.model_copy(update={"start": m.start - d if m.start >= b else min(m.start, a),
                                      "end": m.end - d if m.end >= b else min(m.end, a)})
                 for m in p.markers if not (m.start >= a and m.end <= b)]
    p.markers = [m for m in p.markers if m.end - m.start > 1e-6]
    p.bars = max(1, p.bars - int(round(d / p.beats_per_bar)))


# ---------------------------------------------------------------- ops

class Editor:
    def __init__(self, req: EditRequest):
        self.p = req.project.model_copy(deep=True)
        self.notes: list[str] = []
        self.applied: list[str] = []
        self.style, self.mood, self.harmony = req.style, req.mood, req.harmony
        self.seed = req.seed
        self.b = Builder(req.track_id, self.p, req.seed, self.notes)

    def _energy_at(self, a: float, op_energy: str | None) -> float:
        if op_energy:
            return ENERGY_LEVEL[op_energy]
        mk = next((m for m in self.p.markers if m.start <= a < m.end), None)
        return mk.energy if mk else 0.55

    def _next_seed(self) -> int:
        self.seed = (self.seed * 7 + 13) % (2**31 - 1)
        return self.seed

    def _bars(self, a: float, b: float) -> int:
        return max(1, int(round((b - a) / self.p.beats_per_bar)))

    def _fill_parts(self, parts: list[str], a: float, b: float, energy: str | None, style: str | None = None, mood: str | None = None):
        for part in parts:
            for t in _gen_tracks(self.p, [part]):
                _cut_track(t, a, b)
        self.b.parts(a, self._bars(a, b), parts, style or self.style, mood or self.mood, self.harmony,
                     self._next_seed(), self._energy_at(a, energy))

    def run(self, op: EditOp) -> str:
        p, bpb = self.p, self.p.beats_per_bar
        o = op.op
        if o in ("add_section", "duplicate_section"):
            if p.bars + op.bars > MAX_BARS and o == "add_section":
                raise EditError(f"il progetto supererebbe {MAX_BARS} battute")
        if o == "add_section":
            at = _point(p, op.after)
            length = op.bars * bpb
            insert_gap(p, at, length)
            name = op.name or "nuova parte"
            energy = op.energy or "mid"
            p.markers.append(Marker(start=at, end=at + length, name=name, energy=ENERGY_LEVEL[energy]))
            p.markers.sort(key=lambda m: m.start)
            self.b.samples(at, op.bars, op.sample, op.sample_bars, op.keep, op.fx)
            self.b.parts(at, op.bars, op.parts, op.style or self.style, op.mood or self.mood, self.harmony,
                         self._next_seed(), ENERGY_LEVEL[energy])
            return f"+ sezione «{name}» di {op.bars} battute alla battuta {int(at // bpb) + 1}"
        if o == "remove_section":
            rs = ranges(p, op.section)
            if rs == [(0.0, _total(p))]:
                raise EditError("non posso togliere tutto il pezzo")
            for a, b in sorted(rs, reverse=True):
                delete_range(p, a, b)
            return f"− sezione «{op.section}»" + (f" ({len(rs)} volte)" if len(rs) > 1 else "")
        if o == "duplicate_section":
            rs = ranges(p, op.section)
            a, b = rs[0]
            at = _point(p, op.after) if op.after not in ("end", "") else b
            length = b - a
            if p.bars + length / bpb > MAX_BARS:
                raise EditError(f"il progetto supererebbe {MAX_BARS} battute")
            src = p.model_copy(deep=True)
            insert_gap(p, at, length)
            for st, t in zip(src.tracks, p.tracks):
                items = st.clips if st.kind == "audio" else st.patterns
                split = _split_clip if st.kind == "audio" else _split_pattern
                for c in items:
                    if c.at_beat + c.length_beats <= a or c.at_beat >= b:
                        continue
                    _, rest = split(c, a)
                    piece, _ = split(rest, b) if rest is not None else (None, None)
                    if piece is None:
                        continue
                    copy = piece.model_copy(update={"id": uid(self.b.rng), "at_beat": piece.at_beat - a + at})
                    (t.clips if t.kind == "audio" else t.patterns).append(copy)
            mk = next((m for m in src.markers if m.start <= a < m.end), None)
            if mk:
                p.markers.append(Marker(start=at, end=at + length, name=mk.name, energy=mk.energy))
                p.markers.sort(key=lambda m: m.start)
            p.chords = sorted(p.chords + [c.model_copy(update={"start": c.start - a + at, "end": c.end - a + at})
                                          for c in src.chords if a <= c.start < b], key=lambda c: c.start)
            return f"⧉ «{op.section}» ripetuta alla battuta {int(at // bpb) + 1}"
        if o == "remove":
            if not op.targets:
                raise EditError("niente da togliere")
            for a, b in ranges(p, op.section):
                for t in _gen_tracks(p, op.targets):
                    _cut_track(t, a, b)
                for t in p.tracks:
                    if t.kind == "audio":
                        _cut_track(t, a, b, only=lambda c, t=t: any(_clip_matches(t, c, x) for x in op.targets))
            # Empty generated tracks go away.
            p.tracks = [t for t in p.tracks if t.kind == "audio" or t.patterns]
            return f"− {', '.join(LABEL[x] for x in op.targets)} ({'tutto il pezzo' if op.section.lower() == 'all' else op.section})"
        if o in ("add_parts", "regenerate"):
            parts = [x for x in (op.parts or op.targets) if x in GEN]
            if not parts:
                raise EditError("nessuna parte generata indicata")
            if o == "regenerate" and op.style:
                self.style = op.style
            if o == "regenerate" and op.mood:
                self.mood = op.mood
            secs = ranges(p, op.section)
            if op.section.lower() in ("all", "") and p.markers:
                secs = [(m.start, m.end) for m in p.markers]  # each section with its own energy
            for a, b in secs:
                self._fill_parts(parts, a, b, op.energy)
            verb = "nuove" if o == "add_parts" else "rigenerate"
            return f"↻ {', '.join(LABEL[x] for x in parts)} {verb} ({op.section})"
        if o == "set_fx":
            targets = [x for x in (op.targets or ["vocals"]) if x not in GEN]
            fx = [f for f in op.fx if f != "none"]
            n = 0
            for a, b in ranges(p, op.section):
                for t in list(p.tracks):
                    if t.kind != "audio" or t.name == HARMONY_TRACK:
                        continue
                    hit = lambda c, t=t: any(_clip_matches(t, c, x) for x in targets) and c.at_beat < b and c.at_beat + c.length_beats > a
                    # Split at the range edges so only the range changes.
                    inside = [c for c in t.clips if hit(c)]
                    if not inside:
                        continue
                    t.clips = [c for c in t.clips if not hit(c)]
                    for c in inside:
                        left, rest = _split_clip(c, a)
                        mid, right = _split_clip(rest, b) if rest is not None else (None, None)
                        if left is not None and rest is not None:
                            t.clips.append(left)
                        if right is not None:
                            t.clips.append(right.model_copy(update={"id": uid(self.b.rng)}))
                        if mid is not None:
                            mid = apply_fx(mid.model_copy(update={"id": uid(self.b.rng)}), fx)
                            t.clips.append(mid)
                            n += 1
                            if "harmony" in fx and mid.source == "vocals":
                                h = self.b.audio_track(HARMONY_TRACK, True)
                                if h is not None:
                                    h.gain_db = -5.0
                                    h.clips.append(mid.model_copy(update={"id": uid(self.b.rng), "harmony": 2}))
            if n == 0:
                raise EditError(f"nessuna clip di {', '.join(LABEL[x] for x in targets)} in «{op.section}»")
            return f"✦ {', '.join(LABEL[x] for x in targets)} in «{op.section}»: {', '.join(fx) or 'effetti tolti'}"
        if o == "volume":
            tracks = _tracks_of(p, op.targets)
            if not tracks:
                raise EditError("nessuna traccia da regolare")
            for t in tracks:
                t.gain_db = max(-60.0, min(12.0, t.gain_db + op.value))
            return f"{'▲' if op.value > 0 else '▼'} {', '.join(t.name for t in tracks)} {op.value:+g} dB"
        if o == "tempo":
            if not 40 <= op.value <= 240:
                raise EditError("BPM fuori range (40–240)")
            p.bpm = round(op.value, 1)
            return f"♩ {p.bpm:g} BPM"
        if o == "transpose":
            p.transpose = float(max(-12, min(12, round(op.value))))
            return f"♯ trasposizione {p.transpose:+g} semitoni"
        if o == "style":
            if op.style:
                self.style = op.style
            if op.mood:
                self.mood = op.mood
            parts = [x for x in GEN if _gen_tracks(p, [x])] or ["drums", "bass", "chords"]
            secs = [(m.start, m.end) for m in p.markers] or [(0.0, _total(p))]
            for a, b in secs:
                self._fill_parts(parts, a, b, None)
            return f"✎ strumentale rifatto: {self.style}" + (f", {self.mood}" if op.mood else "")
        if o == "automate":
            if op.shape == "none":
                raise EditError("forma dell'automazione mancante")
            param, v0, v1 = SHAPES[op.shape]
            tracks = _tracks_of(p, op.targets) if op.targets else [t for t in p.tracks if not t.mute]
            if not tracks:
                raise EditError("nessuna traccia da automatizzare")
            for a, b in ranges(p, op.section):
                for t in tracks:
                    pts = [pt for pt in t.automation.get(param, []) if pt.beat < a or pt.beat > b]
                    t.automation[param] = sorted(pts + [AutoPoint(beat=a, value=v0), AutoPoint(beat=b, value=v1)], key=lambda x: x.beat)
            names = {"fade_in": "fade in", "fade_out": "fade out", "filter_open": "filtro che si apre",
                     "filter_close": "filtro che si chiude", "rise": "sale da sotto"}
            return f"〜 {names[op.shape]} su {', '.join(t.name for t in tracks)} ({op.section})"
        if o == "sidechain":
            key = next((t for t in p.tracks if t.kind == "drums"), None) or next(
                (t for t in p.tracks if t.kind == "audio" and t.clips and all(c.source == "drums" for c in t.clips)), None)
            if key is None:
                raise EditError("nessuna traccia di batteria per il sidechain")
            tracks = [t for t in _tracks_of(p, op.targets or ["bass", "chords"]) if t.id != key.id]
            if not tracks:
                raise EditError("nessuna traccia da far pompare")
            amount = op.value if op.value > 0 else 8.0
            for t in tracks:
                t.sidechain = Sidechain(enabled=amount > 0, source=key.id, amount_db=min(30.0, amount), release_ms=t.sidechain.release_ms)
            return f"⇣ sidechain di {', '.join(t.name for t in tracks)} su {key.name} ({amount:g} dB)"
        raise EditError(f"operazione sconosciuta: {o}")


def apply(req: EditRequest, ops: list[EditOp]) -> EditResponse:
    ed = Editor(req)
    for op in ops:
        before = ed.p.model_copy(deep=True)
        try:
            ed.applied.append(ed.run(op))
        except ValueError as e:  # EditError, or a value the schema refuses
            # Roll back a half-applied op.
            ed.p = ed.b.project = before
            ed.notes.append(f"{op.op}: {e}")
    project = ed.b.finish()
    return EditResponse(
        project=project, explanation="", applied=ed.applied, notes=ed.notes,
        style=ed.style, mood=ed.mood, harmony=ed.harmony,
    )
